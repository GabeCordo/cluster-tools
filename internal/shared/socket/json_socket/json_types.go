package json_socket

import (
	"encoding/json"
	"github.com/GabeCordo/Flock/internal/shared/socket"
	"io"
)

//////////////////////////////////////////////////////////////////////////////
//							  		Types
//////////////////////////////////////////////////////////////////////////////

// useTCP
// is a constant used to dial or receive on a network socket.
const useTCP = "tcp"

//////////////////////////////////////////////////////////////////////////////
//							  	Encoders
//////////////////////////////////////////////////////////////////////////////

type EncoderFactory struct {
}

func (eF EncoderFactory) NewEncoder(w io.Writer) socket.Encoder {
	return json.NewEncoder(w)
}

//////////////////////////////////////////////////////////////////////////////
//							  	Decoders
//////////////////////////////////////////////////////////////////////////////

type DecoderFactory struct {
}

func (dF DecoderFactory) NewDecoder(r io.Reader) socket.Decoder {
	return json.NewDecoder(r)
}
